// Dumps Intl day/month names (en and ar with Latin digits) into core/src/fmt_data.rs, and a fixture of formatted dates.
// Usage: node rust-app/tools/gen_fmt.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const LOCS = { en: 'en-US', ar: 'ar-u-nu-latn' };
const f = (loc, o, d) => new Intl.DateTimeFormat(loc, o).format(d);
const names = (loc) => ({
  wd_long: [...Array(7)].map((_, i) => f(loc, { weekday: 'long' }, new Date(2024, 0, 7 + i))),
  wd_short: [...Array(7)].map((_, i) => f(loc, { weekday: 'short' }, new Date(2024, 0, 7 + i))),
  wd_narrow: [...Array(7)].map((_, i) => f(loc, { weekday: 'narrow' }, new Date(2024, 0, 7 + i))),
  mon_long: [...Array(12)].map((_, i) => f(loc, { month: 'long' }, new Date(2024, i, 1))),
  mon_short: [...Array(12)].map((_, i) => f(loc, { month: 'short' }, new Date(2024, i, 1))),
});
const q = (a) => '[' + a.map((s) => JSON.stringify(s)).join(', ') + ']';
let rs = '//! Generated by tools/gen_fmt.mjs from Intl. Do not edit.\n';
for (const [k, loc] of Object.entries(LOCS)) {
  const n = names(loc), U = k.toUpperCase();
  rs += `pub const ${U}_WD_LONG: [&str; 7] = ${q(n.wd_long)};\npub const ${U}_WD_SHORT: [&str; 7] = ${q(n.wd_short)};\npub const ${U}_WD_NARROW: [&str; 7] = ${q(n.wd_narrow)};\n`;
  rs += `pub const ${U}_MON_LONG: [&str; 12] = ${q(n.mon_long)};\npub const ${U}_MON_SHORT: [&str; 12] = ${q(n.mon_short)};\n`;
  const am = f(loc, { hour: 'numeric', minute: '2-digit', hour12: true }, new Date(2000, 0, 1, 1, 5));
  const pm = f(loc, { hour: 'numeric', minute: '2-digit', hour12: true }, new Date(2000, 0, 1, 13, 5));
  rs += `pub const ${U}_AM: &str = ${JSON.stringify(am.replace(/^1:05/, ''))};\npub const ${U}_PM: &str = ${JSON.stringify(pm.replace(/^1:05/, ''))};\n`;
}
fs.writeFileSync(path.join(HERE, '..', 'core', 'src', 'fmt_data.rs'), rs);
// Fixture: every combination the app uses, for dates across several years.
const dates = [];
for (let y of [2024, 2026, 2027]) for (let m = 0; m < 12; m++) for (let d of [1, 9, 15, 28]) dates.push(new Date(y, m, d, (m * 7 + d) % 24, (m * 13 + d) % 60));
const out = [];
for (const [k, loc] of Object.entries(LOCS)) for (const d of dates) {
  const pad = (n) => String(n).padStart(2, '0');
  out.push({
    lang: k, date: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`, min: d.getHours() * 60 + d.getMinutes(),
    day_full: f(loc, { weekday: 'short', month: 'short', day: 'numeric', year: 'numeric' }, d),
    day_md: f(loc, { month: 'short', day: 'numeric' }, d),
    wd_md: f(loc, { weekday: 'short', month: 'short', day: 'numeric' }, d),
    month_long: f(loc, { month: 'long' }, d),
    month_year: f(loc, { month: 'long', year: 'numeric' }, d),
    t_auto: f(loc, { hour: 'numeric', minute: '2-digit' }, new Date(2000, 0, 1, d.getHours(), d.getMinutes())),
    t_12: f(loc, { hour: 'numeric', minute: '2-digit', hour12: true }, new Date(2000, 0, 1, d.getHours(), d.getMinutes())),
    t_24: f(loc, { hour: 'numeric', minute: '2-digit', hourCycle: 'h23' }, new Date(2000, 0, 1, d.getHours(), d.getMinutes())),
  });
}
fs.writeFileSync(path.join(HERE, '..', 'core', 'tests', 'fixtures', 'fmt.json'), JSON.stringify(out, null, 1));
console.log('dates', out.length, JSON.stringify(out[5]));
